/** Сұрақтың тақырып шеңберіне сәйкестігін тексеру. */
export function checkScope(question: string): ScopeVerdict {
  const t = norm(question);

  if (SUPPORT_WORDS.some((w) => hasWord(t, w))) {
    return {
      kind: 'support',
      reply:
        'Сенің қауіпсіздігің мен көңіл-күйің бәрінен маңызды 💙\n' +
        'Өтінемін, бұл жағдайды жалғыз шешуге тырыспа — сынып жетекшіңе, ата-анаңа немесе мектеп психологына дереу айт.\n' +
        'Қазақстанда тәулік бойы жұмыс істейтін балалар сенім телефоны: **111**.\n' +
        'Мен саған оқу мәселелерінде әрқашан көмектесе аламын.',
    };
  }

  const isEdu = EDU_HINTS.some((w) => hasWord(t, w));

  for (const b of BLOCKED) {
    if (b.words.some((w) => hasWord(t, w)) && !isEdu) {
      return {
        kind: 'refuse',
        topic: b.label,
        reply: OFF_TOPIC_REPLY,
      };
    }
  }

  return { kind: 'allow' };
}
