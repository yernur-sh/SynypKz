const SUPPORT_WORDS = ['өзіме қол', 'өлгім', 'суицид', 'самоубийств', 'булл', 'қорлайды', 'ұрады', 'мазақ ет'];

function norm(s: string) {
  return s.toLowerCase().replace(/ё/g, 'е').trim();
}

/** Қысқа сөздер (ұбт, ент, сор...) басқа сөздің ішінде кездеспеуі үшін — сөз шекарасымен іздейміз. */
function hasWord(text: string, word: string): boolean {
  if (word.length >= 5) return text.includes(word);
  const esc = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|[^\\p{L}\\p{N}])${esc}([^\\p{L}\\p{N}]|$)`, 'u').test(text);
}

export type ScopeVerdict =
  | { kind: 'allow' }
  | { kind: 'support'; reply: string }
  | { kind: 'refuse'; reply: string; topic: string };

