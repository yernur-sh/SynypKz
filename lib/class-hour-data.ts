export function directionOf(key: DirectionKey) {
  return DIRECTIONS.find((d) => d.key === key) ?? DIRECTIONS[0];
}

export function monthLabel(key: MonthKey) {
  return MONTHS.find((m) => m.key === key)?.label ?? '';
}

