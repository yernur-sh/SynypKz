// ЖИ-көмекшінің жүйелік нұсқаулығы (system prompt) + сынып контексті.
// Серверлік API route осы мәтінді модельге жібереді.

import { CLASS_LABEL, DAYS } from './config';
import {
  WEEK_SCHEDULE,
  TOTAL_LESSONS,
  SUBJECTS,
  lessonsFor,
  todayKey,
  tomorrowKey,
  nextSchoolDayKey,
  dayLabel,
} from './schedule-data';
import { CLASS_HOUR_PLAN, MONTHS, currentWeek, directionOf, monthLabel } from './class-hour-data';

/** Сынып деректерін қысқа мәтінге жинау (модель контексті үшін). */
export function buildClassContext(now = new Date()): string {
  const scheduleText = DAYS.map((d) => {
    const ls = lessonsFor(d.key);
    if (!ls.length) return `${d.label}: сабақ жоқ (демалыс)`;
    return `${d.label}: ${ls
      .map((l) => `${l.lessonNumber}) ${l.time} ${l.subject} — ${l.teacher}, ${l.room}`)
      .join('; ')}`;
  }).join('\n');

  const today = todayKey(now);
  const tomorrow = tomorrowKey(now);
  const next = nextSchoolDayKey(now);

  const cur = currentWeek(now);
  const planText = MONTHS.map((m) => {
    const weeks = CLASS_HOUR_PLAN.filter((w) => w.month === m.key);
    if (!weeks.length) return '';
    const rows = weeks
      .map(
        (w) =>
          `  ${w.week}-апта: ` +
          w.topics.map((t) => `[${directionOf(t.direction).short}] ${t.title}`).join(' | ')
      )
      .join('\n');
    return `${m.label}:\n${rows}`;
  })
    .filter(Boolean)
    .join('\n');

  return [
    `СЫНЫП: ${CLASS_LABEL}. Аптасына ${TOTAL_LESSONS} сабақ, ${SUBJECTS.length} пән.`,
    `БҮГІНГІ КҮН: ${now.toLocaleDateString('kk-KZ')} — ${dayLabel(today)}${
      today === null || lessonsFor(today).length === 0 ? ' (демалыс, сабақ жоқ)' : ''
    }.`,
    `ЕРТЕҢ: ${dayLabel(tomorrow)}${
      tomorrow === null || lessonsFor(tomorrow).length === 0 ? ' (демалыс, сабақ жоқ)' : ''
    }. Келесі оқу күні: ${dayLabel(next)}.`,
    `МАҢЫЗДЫ: аптада жексенбі де бар және ол демалыс күні. Сенбіден кейін жексенбі келеді, дүйсенбі емес.`,
    '',
    'АПТАЛЫҚ КЕСТЕ:',
    scheduleText,
    '',
    'ТӘРБИЕ САҒАТЫ (2026-2027 оқу жылының бекітілген тақырыптары, апта сайын):',
    planText,
    cur
      ? `ОСЫ АПТАНЫҢ ТАҚЫРЫБЫ (${monthLabel(cur.month)} ${cur.week}-апта): ` +
        cur.topics.map((t) => `«${t.title}»`).join('; ')
      : 'Қазір жоспарда тәрбие сағаты тақырыбы жоқ (демалыс кезеңі).',
  ].join('\n');
}

